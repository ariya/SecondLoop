package secondloop;

import java.io.PrintWriter;
import java.io.StringWriter;

/**
 * Helpers written in the REPL language itself, evaluated into the global
 * environment at startup. Anything defined here can be redefined from the REPL.
 */
public final class Prelude {
    static final String SOURCE = ""
            + "(defn clamp\n"
            + "  \"Limits x to the range lo..hi, e.g. (clamp power -1 1).\"\n"
            + "  [x lo hi]\n"
            + "  (max lo (min hi x)))\n"
            + "\n"
            + "(defn deadband\n"
            + "  \"0 when x is within width of zero, e.g. to ignore joystick drift.\"\n"
            + "  [x width]\n"
            + "  (if (< (abs x) width) 0 x))\n"
            + "\n"
            + "(defn lerp\n"
            + "  \"a when t is 0, b when t is 1, and in between for 0 < t < 1.\"\n"
            + "  [a b t]\n"
            + "  (+ a (* t (- b a))))\n"
            + "\n"
            + "(defn wrap-degrees\n"
            + "  \"The same angle within -180..180 (exclusive of 180), e.g. for heading error.\"\n"
            + "  [deg]\n"
            + "  (- (mod (+ deg 180) 360) 180))\n"
            + "\n"
            + "(defn wrap-radians\n"
            + "  \"The same angle within -PI..PI (exclusive of PI).\"\n"
            + "  [rad]\n"
            + "  (- (mod (+ rad Math/PI) (* 2 Math/PI)) Math/PI))\n"
            + "\n"
            + "(defn partial\n"
            + "  \"f with its first arguments filled in, e.g. ((partial clamp 1.5) -1 1).\"\n"
            + "  [f & args]\n"
            + "  (fn [& more] (apply f (concat args more))))\n"
            + "\n"
            + "(defn comp\n"
            + "  \"Chains functions right to left: ((comp f g) x) is (f (g x)).\"\n"
            + "  [& fs]\n"
            + "  (if (empty? fs)\n"
            + "    (fn [x] x)\n"
            + "    (reduce (fn [f g] (fn [& args] (f (apply g args)))) fs)))\n"
            + "\n"
            + "(defn constantly\n"
            + "  \"A function that ignores its arguments and always gives x.\"\n"
            + "  [x]\n"
            + "  (fn [& args] x))\n"
            + "\n"
            + ";; The control loop running in the background, shared by every connection.\n"
            + "(def control/current (atom nil))\n"
            + "\n"
            + "(defn control/stop\n"
            + "  \"Stops the loop started by control/start. True if one was running.\"\n"
            + "  []\n"
            + "  (let [f @control/current]\n"
            + "    (if f (future-cancel f) false)))\n"
            + "\n"
            + "(defn control/start\n"
            + "  \"Runs (f) in the background, so the REPL stays free. Any loop started\n"
            + "  earlier is stopped first, so only one loop drives the robot at a time.\"\n"
            + "  [f]\n"
            + "  (control/stop)\n"
            + "  (reset! control/current (future (f))))\n"
            + "\n"
            + "(defn control/running?\n"
            + "  \"True while the loop started by control/start is still running.\"\n"
            + "  []\n"
            + "  (let [f @control/current]\n"
            + "    (if f (not (future-done? f)) false)))\n"
            + "\n"
            + "(defn publish/setup\n"
            + "  \"Publishes values to subscribers on port 5599, e.g.\n"
            + "  (publish/setup {:battery battery/voltage}), or on another port, e.g.\n"
            + "  (publish/setup 6789 {:battery battery/voltage}). Each value is a function of\n"
            + "  no arguments, or an atom to read. Each subscriber gets its own loop in the\n"
            + "  background, reading them at the rate it asked for, until the next\n"
            + "  publish/setup.\"\n"
            + "  [& args]\n"
            + "  (when-not (or (= (count args) 1) (= (count args) 2))\n"
            + "    (throw (ex-info (str \"publish/setup expects an optional port and a map of fields,\"\n"
            + "                         \" such as (publish/setup 6789 {:battery battery/voltage})\")\n"
            + "                    {})))\n"
            + "  (let [port (if (= (count args) 2) (first args) nil)\n"
            + "        fields (last args)]\n"
            + "    (when-not (or (nil? port)\n"
            + "                  (and (number? port) (= port (Math/floor port)) (<= 1 port 65535)))\n"
            + "      (throw (ex-info (str \"publish/setup expects a port from 1 to 65535, got: \" (pr-str port))\n"
            + "                      {})))\n"
            + "    (when-not (and (map? fields) (not (empty? fields))\n"
            + "                   (every? (fn [v] (or (fn? v) (atom? v))) (vals fields)))\n"
            + "      (throw (ex-info (str \"publish/setup expects a map of field names to functions or atoms,\"\n"
            + "                           \" such as {:battery battery/voltage}, got: \" (pr-str fields))\n"
            + "                      {})))\n"
            + "    (doseq [k (keys fields)]\n"
            + "      (when-not (or (keyword? k) (string? k))\n"
            + "        (throw (ex-info (str \"publish/setup expects keyword or string field names, got: \"\n"
            + "                             (pr-str k))\n"
            + "                        {})))\n"
            + "      ;; The protocol separates fields with \",\" and \";\", and commands with spaces.\n"
            + "      (when (or (str/blank? (name k))\n"
            + "                (some (fn [c] (str/includes? (name k) c)) [\",\" \";\" \"=\" \" \"]))\n"
            + "        (throw (ex-info (str \"publish/setup cannot use the field name: \" (pr-str k)) {}))))\n"
            + "    (when-not (= (count fields) (count (set (map name (keys fields)))))\n"
            + "      (throw (ex-info \"publish/setup has the same field name twice\" {})))\n"
            + "    (let [read (fn [v] (if (atom? v) (fn [] (deref v)) v))\n"
            + "          by-name (reduce (fn [m [k v]] (assoc m (name k) (read v))) {} fields)\n"
            + "          ;; Sorted by name, so SUB ALL gives the same columns whatever order the map has.\n"
            + "          ordered (map (fn [n] [n (get by-name n)]) (sort (keys by-name)))\n"
            + "          sample (fn [] (reduce (fn [m [n f]] (assoc m n (f))) {} ordered))]\n"
            + "      ;; One sample now checks every function and gives each field its type.\n"
            + "      (publish/start port (sample) sample))))\n";

    private Prelude() {
    }

    public static void load(Env globals) {
        Interp interp = new Interp(globals, new PrintWriter(new StringWriter()));
        for (Object form : Reader.readAll(SOURCE)) {
            interp.evalTopLevel(form);
        }
    }
}
